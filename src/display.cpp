// ── Backlight ─────────────────────────────────────────────────
// GPIO38 wird ausschließlich von main.cpp per LEDC gesteuert.
// display.cpp verwaltet nur das Flag, kein analogWrite/digitalWrite.
#define DISPLAY_BACKLIGHT_PIN 38

void Arduino_4848_Display::begin() {
    Arduino_RGB_Display::begin();
    // pinMode NICHT hier – LEDC in main.cpp übernimmt GPIO38
    blON = false;
}


void Arduino_4848_Display::setBacklight(bool on) {
    blON = on;   // nur Flag – kein GPIO-Zugriff hier
}

void Arduino_4848_Display::setBrightness(uint8_t value) {
    _brightness = value;
}

bool Arduino_4848_Display::isBacklightOn() {
    return blON;
}
